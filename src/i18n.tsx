function normalizeTranslationKey(text: string): string {
  return text.trim().replace(/\s+/g, ' ').replace(/[‘’]/g, "'");
}

const normalizedTranslations: Record<Exclude<Language, 'en'>, Record<string, string>> = {
  am: Object.fromEntries(Object.entries(translations.am).map(([key, value]) => [normalizeTranslationKey(key), value])),
  om: Object.fromEntries(Object.entries(translations.om).map(([key, value]) => [normalizeTranslationKey(key), value])),
};

function readSavedLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem('medresah-language');
    return saved === 'am' || saved === 'om' ? saved : 'en';
  } catch {
    return 'en';
  }
}

let activeLanguage: Language = readSavedLanguage();

export function translate(text: string, values?: Record<string, string | number>): string {
  const translated = activeLanguage === 'en'
    ? text
    : normalizedTranslations[activeLanguage][normalizeTranslationKey(text)] ?? text;
  return values
    ? translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
    : translated;
}

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(activeLanguage);
  const setLanguage = useCallback((next: Language) => {
    activeLanguage = next;
    setLanguageState(next);
    try {
      window.localStorage.setItem('medresah-language', next);
    } catch (error) {
      console.error('Could not save the selected language:', error);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage }), [language, setLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function LanguageBoundary({ children }: { children: ReactNode }) {
  const { language } = useLanguage();
  return <Fragment key={language}>{children}</Fragment>;
}

export function LanguageSelector() {
  const { language, setLanguage } = useLanguage();
  const [isOpen, setIsOpen] = useState(false);
  const options: { value: Language; label: string }[] = [
    { value: 'en', label: 'English' },
    { value: 'am', label: 'አማርኛ' },
    { value: 'om', label: 'Afaan Oromoo' },
  ];

  return (
    <div className="relative">
      <button
        type="button"
        aria-label={translate('Language')}
        aria-expanded={isOpen}
        aria-controls="language-options"
        title={translate('Language')}
        onClick={() => setIsOpen((open) => !open)}
        className="inline-flex h-10 w-10 items-center justify-center rounded-lg border border-slate-300 bg-white text-slate-600 hover:bg-slate-50 focus:border-orange-500 focus:outline-none focus:ring-2 focus:ring-orange-500/30"
      >
        <Languages className="h-5 w-5" aria-hidden="true" />
      </button>
      {isOpen && (
        <div
          id="language-options"
          role="group"
          aria-label={translate('Language')}
          className="absolute right-0 top-full z-50 mt-2 min-w-40 rounded-lg border border-slate-200 bg-white p-1 shadow-lg"
        >
          {options.map((option) => (
            <button
              key={option.value}
              type="button"
              aria-current={language === option.value ? 'true' : undefined}
              onClick={() => {
                setLanguage(option.value);
                setIsOpen(false);
              }}
              className={`block w-full rounded-md px-3 py-2 text-left text-sm hover:bg-slate-100 ${
                language === option.value ? 'font-semibold text-orange-700' : 'text-slate-700'
              }`}
            >
              {option.label}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
